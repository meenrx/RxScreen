/**
 * แปลงข้อความที่พิมพ์ผิด layout (ลืมสลับเป็น EN → ได้อักษรไทย Kedmanee)
 * กลับเป็นอังกฤษตามตำแหน่งปุ่มจริง — ใช้กับการสแกน QR ด้วยเครื่องสแกน (คีย์บอร์ด)
 * ตรวจสอบ round-trip แล้ว: พิมพ์ payload บน layout ไทย → แปลงกลับได้ payload เดิม
 */

// ตารางปุ่ม Kedmanee: [en(ปกติ), en(shift), thai(ปกติ), thai(shift)]
const KEYS: [string, string, string, string][] = [
  ['`', '~', '_', '%'], ['1', '!', 'ๅ', '+'], ['2', '@', '/', '๑'], ['3', '#', '-', '๒'], ['4', '$', 'ภ', '๓'],
  ['5', '%', 'ถ', '๔'], ['6', '^', 'ุ', 'ู'], ['7', '&', 'ึ', '฿'], ['8', '*', 'ค', '๕'], ['9', '(', 'ต', '๖'],
  ['0', ')', 'จ', '๗'], ['-', '_', 'ข', '๘'], ['=', '+', 'ช', '๙'],
  ['q', 'Q', 'ๆ', '๐'], ['w', 'W', 'ไ', '"'], ['e', 'E', 'ำ', 'ฎ'], ['r', 'R', 'พ', 'ฑ'], ['t', 'T', 'ะ', 'ธ'],
  ['y', 'Y', 'ั', 'ํ'], ['u', 'U', 'ี', '๊'], ['i', 'I', 'ร', 'ณ'], ['o', 'O', 'น', 'ฯ'], ['p', 'P', 'ย', 'ญ'],
  ['[', '{', 'บ', 'ฐ'], [']', '}', 'ล', ','], ['\\', '|', 'ฃ', 'ฅ'],
  ['a', 'A', 'ฟ', 'ฤ'], ['s', 'S', 'ห', 'ฆ'], ['d', 'D', 'ก', 'ฏ'], ['f', 'F', 'ด', 'โ'], ['g', 'G', 'เ', 'ฌ'],
  ['h', 'H', '้', '็'], ['j', 'J', '่', '๋'], ['k', 'K', 'า', 'ษ'], ['l', 'L', 'ส', 'ศ'], [';', ':', 'ว', 'ซ'],
  ["'", '"', 'ง', '.'],
  ['z', 'Z', 'ผ', '('], ['x', 'X', 'ป', ')'], ['c', 'C', 'แ', 'ฉ'], ['v', 'V', 'อ', 'ฮ'], ['b', 'B', 'ิ', 'ฺ'],
  ['n', 'N', 'ื', '์'], ['m', 'M', 'ท', '?'], [',', '<', 'ม', 'ฒ'], ['.', '>', 'ใ', 'ฬ'], ['/', '?', 'ฝ', 'ฦ'],
]

// map: อักษรไทย (จากปุ่มนั้น) → อักษรอังกฤษที่ควรจะเป็น
const TH_TO_EN: Record<string, string> = {}
for (const [en, sh, thn, ths] of KEYS) {
  TH_TO_EN[thn] = en
  TH_TO_EN[ths] = sh
}

/** มีอักษรไทยในข้อความไหม (บ่งชี้ว่าอาจพิมพ์ผิด layout) */
export function hasThai(s: string): boolean {
  return /[฀-๿]/.test(s)
}

/** แปลงทุกตัวอักษรจาก layout ไทย → อังกฤษตามตำแหน่งปุ่ม (ตัวที่ไม่รู้จักปล่อยผ่าน) */
export function fixThaiLayout(s: string): string {
  return [...s].map((c) => TH_TO_EN[c] ?? c).join('')
}
